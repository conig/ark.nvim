vim.opt.rtp:prepend(vim.fn.getcwd())

-- Persistence uses real disk IO; separate handles model simultaneous consoles.
local history = require("ark.console_history")
local directory = vim.fn.tempname()
vim.fn.mkdir(directory .. "/project/.git", "p")
vim.fn.mkdir(directory .. "/project/sub", "p")
vim.fn.mkdir(directory .. "/other", "p")
local options = { enabled = true, directory = directory .. "/history", max_entries = 3 }
local first = history.open(directory .. "/project", options, { ".git" })
local second = history.open(directory .. "/project/sub", options, { ".git" })
assert(first.path == second.path, "nested project directories must share history")
assert(history.append(first, "one()"))
assert(history.append(second, "two(\n  2\n)"))
assert(history.append(first, "three()"))
assert(history.append(second, "four()"))
assert(vim.deep_equal(history.load(first), { "two(\n  2\n)", "three()", "four()" }))
local reopened = history.open(directory .. "/project", options, { ".git" })
assert(vim.deep_equal(history.load(reopened), history.load(first)))
assert(#history.load(history.open(directory .. "/other", options, { ".git" })) == 0)
assert(vim.fn.getfperm(first.path) == "rw-------")
-- Malformed/truncated records cannot prevent subsequent valid commands loading.
vim.fn.writefile({ '{"broken":' }, first.path, "ab")
assert(history.append(first, "after_corruption()"))
assert(history.load(first)[3] == "after_corruption()")
local disabled = history.open(directory .. "/project", { enabled = false }, { ".git" })
assert(disabled.path == nil and #history.load(disabled) == 0)
assert(history.append(disabled, "not_saved()"))
assert(history.load(first)[3] == "after_corruption()")
vim.fn.delete(directory, "rf")
